// Merges openapi/base.yaml with every openapi/modules/*.yaml into openapi/openapi.yaml.
// Each module owns its paths and component names; duplicates fail the build so two
// modules can never silently overwrite each other's definitions.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "openapi.yaml");
const check = process.argv.includes("--check");

const base = YAML.parse(readFileSync(join(here, "base.yaml"), "utf8"));
const doc = { ...base, paths: {}, components: {} };

const files = readdirSync(join(here, "modules"))
  .filter((f) => f.endsWith(".yaml"))
  .sort();

for (const file of files) {
  const mod = YAML.parse(readFileSync(join(here, "modules", file), "utf8")) ?? {};
  for (const [path, item] of Object.entries(mod.paths ?? {})) {
    if (doc.paths[path]) throw new Error(`${file}: duplicate path ${path}`);
    doc.paths[path] = item;
  }
  for (const [section, entries] of Object.entries(mod.components ?? {})) {
    doc.components[section] ??= {};
    for (const [name, value] of Object.entries(entries)) {
      if (doc.components[section][name]) {
        throw new Error(`${file}: duplicate component ${section}.${name}`);
      }
      doc.components[section][name] = value;
    }
  }
}

const header =
  "# GENERATED by openapi/bundle.mjs from base.yaml + modules/*.yaml. Do not edit by hand.\n";
const text = header + YAML.stringify(doc, { lineWidth: 120, aliasDuplicateObjects: false });

if (check) {
  const current = readFileSync(out, "utf8");
  if (current !== text) {
    console.error("openapi/openapi.yaml is out of date; run `pnpm openapi:bundle`.");
    process.exit(1);
  }
  console.log("openapi bundle up to date");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${files.length} modules)`);
}
