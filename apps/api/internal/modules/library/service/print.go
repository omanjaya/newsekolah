// Labels and membership cards are printed server-side, the same way the
// permits module renders its letters (platform/documents), rather than in
// the browser: the client only ever downloads a finished PDF. Unlike a
// warning letter or a leave letter these are reprintable shop-floor
// artifacts, not audited documents, so they are rendered on demand and
// never numbered, stored as an asset, or given a verification code.
// Copy labels and membership cards are both exceptions to the shared
// documents.Renderer (platform/documents has no barcode-drawing
// primitive and strips <img> tags down to nothing -- see its package
// doc comment): both render directly with fpdf so each can carry a real
// Code 128 barcode image of the member/copy number, generated by the
// same generateCode128PNG helper (service/labels.go). Only the
// clearance letter, a plain-text letter with no barcode, still goes
// through documents.Renderer.

const clearanceLetterTemplate = `
<h1>{{.SchoolName}}</h1>
<h2>Surat Keterangan Bebas Pustaka</h2>
<p>Menerangkan bahwa:</p>
<p>Nama: {{.MemberName}}</p>
<p>No. Anggota: {{.MemberNo}}</p>
<p>Kelas: {{.ClassName}}</p>
<p>Tidak memiliki pinjaman aktif maupun denda yang belum diselesaikan pada Perpustakaan {{.SchoolName}} per tanggal {{.IssuedOn}}.</p>
`

// PrintCopyLabel renders one copy's spine/barcode label as a single-label
// PDF, delegating to the batch renderer (old app kept a single-item
// convenience endpoint alongside the batch one; the rebuild does the
// same by reusing it rather than a second template).
func (s *Service) PrintCopyLabel(ctx context.Context, tenantID, copyID uuid.UUID) ([]byte, error) {
	return s.PrintCopyLabels(ctx, tenantID, []uuid.UUID{copyID})
}

// memberCardInfo is what the printed card and the clearance letter both
// need about one member: display name, member number, class, and
// validity. A zero MemberNo ("-") means the user is not (yet) a
// registered library_members row -- a card can still be printed for
// them, same as the old app.
type memberCardInfo struct {
	SchoolName string
	MemberName string
	MemberNo   string
	ClassName  string
	ValidUntil string
}

// memberCardInfoFromMember builds memberCardInfo from an already-fetched
// domain.Member, so the bulk print path (which lists members once) never
// re-queries library_members per card.
func (s *Service) memberCardInfoFromMember(ctx context.Context, tenantID uuid.UUID, schoolName string, member domain.Member) memberCardInfo {
	name := member.UserID.String()
	if s.members != nil {
		if resolved, err := s.members.UserDisplayName(ctx, tenantID, member.UserID); err == nil && resolved != "" {
			name = resolved
		}
	}
	className, _ := s.repo.GetActiveClassNameForStudent(ctx, tenantID, member.UserID)
	validUntil := "-"
	if member.ValidUntil != nil {
		validUntil = member.ValidUntil.Format("2006-01-02")
	}
	return memberCardInfo{
		SchoolName: schoolName, MemberName: name, MemberNo: member.MemberNo,
		ClassName: className, ValidUntil: validUntil,
	}
}

// memberCardInfoFor resolves everything the card and clearance letter
// need for one member, falling back gracefully when the member or class
// directory lookups come up empty (a card can still be printed for a
// user who is not yet a registered library_members row).
func (s *Service) memberCardInfoFor(ctx context.Context, tenantID, memberUserID uuid.UUID) memberCardInfo {
	schoolName := ""
	if policy, err := s.Policy(ctx, tenantID); err == nil {
		schoolName = policy.Name
	}
	if member, found, err := s.repo.GetMember(ctx, tenantID, memberUserID); err == nil && found {
		return s.memberCardInfoFromMember(ctx, tenantID, schoolName, member)
	}
	name := memberUserID.String()
	if s.members != nil {
		if resolved, err := s.members.UserDisplayName(ctx, tenantID, memberUserID); err == nil && resolved != "" {
			name = resolved
		}
	}
	className, _ := s.repo.GetActiveClassNameForStudent(ctx, tenantID, memberUserID)
	return memberCardInfo{SchoolName: schoolName, MemberName: name, MemberNo: "-", ClassName: className, ValidUntil: "-"}
}

// cardBarcodeHeightMM is the Code 128 image's drawn height on one ATM-sized
// card (old app: library_cards.go's drawLibraryMemberCard).
const cardBarcodeHeightMM = 7.0

// drawMemberCard renders one card at (x, y): a bordered box with the
// school name, member name, member number, class, validity, and a Code
// 128 barcode of the member number -- the same generateCode128PNG helper
// PrintCopyLabels uses for copy labels. imageName must be unique across a
// single PDF (the caller passes a per-card index) since fpdf keys
// registered images by name.
func drawMemberCard(pdf *fpdf.Fpdf, x, y float64, card memberCardInfo, imageName string) {
	const w, h = domain.CardWidthMM, domain.CardHeightMM

	pdf.SetLineWidth(0.3)
	pdf.Rect(x, y, w, h, "D")

	pdf.SetFont("Helvetica", "B", 8)
	pdf.SetXY(x+3, y+3)
	pdf.CellFormat(w-6, 4, card.SchoolName, "", 1, "C", false, 0, "")

	pdf.SetFont("Helvetica", "", 6.5)
	pdf.SetXY(x+3, y+7.5)
	pdf.CellFormat(w-6, 3, "KARTU ANGGOTA PERPUSTAKAAN", "", 1, "C", false, 0, "")

	pdf.SetFont("Helvetica", "B", 10)
	pdf.SetXY(x+3, y+13)
	pdf.CellFormat(w-6, 5, card.MemberName, "", 1, "L", false, 0, "")

	pdf.SetFont("Helvetica", "", 7.5)
	pdf.SetXY(x+3, y+19)
	pdf.CellFormat(w-6, 4, "No. Anggota: "+card.MemberNo, "", 1, "L", false, 0, "")

	className := card.ClassName
	if className == "" {
		className = "-"
	}
	pdf.SetXY(x+3, y+23)
	pdf.CellFormat(w-6, 4, "Kelas: "+className, "", 1, "L", false, 0, "")

	pdf.SetXY(x+3, y+27)
	pdf.CellFormat(w-6, 4, "Berlaku s.d.: "+card.ValidUntil, "", 1, "L", false, 0, "")

	if imgBytes, err := generateCode128PNG(card.MemberNo); err == nil {
		pdf.RegisterImageOptionsReader(imageName, fpdf.ImageOptions{ImageType: "PNG"}, bytes.NewReader(imgBytes))
		pdf.ImageOptions(imageName, x+3, y+h-11, w-6, cardBarcodeHeightMM, false, fpdf.ImageOptions{ImageType: "PNG"}, 0, "")
	}
	pdf.SetFont("Helvetica", "", 6)
	pdf.SetXY(x+3, y+h-3.5)
	pdf.CellFormat(w-6, 3, card.MemberNo, "", 1, "C", false, 0, "")
}

// renderMemberCardsPDF lays out cards on an A4 sheet, domain.CardsPerPage
// (2x5, ATM-sized) to a page, in the given order (old app: library_cards.go's
// libraryCardsPDF).
func renderMemberCardsPDF(cards []memberCardInfo) ([]byte, error) {
	if len(cards) == 0 {
		return nil, domain.ErrMemberNotFound
	}

	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetAutoPageBreak(false, 0)

	for i, card := range cards {
		indexInPage := i % domain.CardsPerPage
		if indexInPage == 0 {
			pdf.AddPage()
		}
		x, y := domain.CardPosition(indexInPage)
		drawMemberCard(pdf, x, y, card, fmt.Sprintf("member-card-barcode-%d", i))
	}

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, fmt.Errorf("render member cards pdf: %w", err)
	}
	return buf.Bytes(), nil
}

// PrintMemberCard renders a member's library card as a PDF: name, member
// number, class, validity, and a Code 128 barcode of the member number
// (old app: library_cards.go:32-153).
func (s *Service) PrintMemberCard(ctx context.Context, tenantID, memberUserID uuid.UUID) ([]byte, error) {
	if err := s.requireEnabled(ctx, tenantID); err != nil {
		return nil, err
	}
	var info memberCardInfo
	if err := s.withTx(ctx, tenantID, func(ctx context.Context) error {
		info = s.memberCardInfoFor(ctx, tenantID, memberUserID)
		return nil
	}); err != nil {
		return nil, err
	}
	return renderMemberCardsPDF([]memberCardInfo{info})
}

// MemberCardFilter selects which members PrintMemberCards prints for:
// exactly one of an explicit MemberIDs list (printed in the given order),
// MemberTypeID, or ClassID (current active enrollment; ordered by name).
// MemberTypeID and ClassID may be combined with each other (both narrow
// the same listing), but never with MemberIDs.
type MemberCardFilter struct {
	MemberIDs    []uuid.UUID
	MemberTypeID uuid.NullUUID
	ClassID      uuid.NullUUID
}

// PrintMemberCards renders up to domain.CardMaxPerPrint members' cards as
// one A4 PDF, the batch counterpart to PrintMemberCard (old app printed by
// an explicit user_ids list only, library_cards.go:18-101; the rebuild
// adds the member-type and class filters the members screen already
// offers, so a whole roster can be printed without collecting every id
// client-side first).
func (s *Service) PrintMemberCards(ctx context.Context, tenantID uuid.UUID, filter MemberCardFilter) ([]byte, error) {
	if err := s.requireEnabled(ctx, tenantID); err != nil {
		return nil, err
	}
	hasIDs := len(filter.MemberIDs) > 0
	hasFilter := filter.MemberTypeID.Valid || filter.ClassID.Valid
	if hasIDs == hasFilter {
		// Neither given, or an id list mixed with a type/class filter:
		// exactly one selection mode is required.
		return nil, domain.ErrInvalidInput
	}
	if hasIDs && len(filter.MemberIDs) > domain.CardMaxPerPrint {
		return nil, domain.ErrInvalidInput
	}

	var members []domain.Member
	err := s.withTx(ctx, tenantID, func(ctx context.Context) error {
		var err error
		if hasIDs {
			members, err = s.repo.GetMembersByIDs(ctx, tenantID, filter.MemberIDs)
			return err
		}
		members, err = s.repo.ListMembersForCardPrint(ctx, tenantID, MemberCardListFilter{
			MemberTypeID: filter.MemberTypeID, ClassID: filter.ClassID,
		}, domain.CardMaxPerPrint)
		return err
	})
	if err != nil {
		return nil, err
	}
	if hasIDs {
		members = orderMembersByIDs(members, filter.MemberIDs)
	}
	if len(members) == 0 {
		return nil, domain.ErrMemberNotFound
	}

	var cards []memberCardInfo
	err = s.withTx(ctx, tenantID, func(ctx context.Context) error {
		schoolName := ""
		if policy, err := s.Policy(ctx, tenantID); err == nil {
			schoolName = policy.Name
		}
		cards = make([]memberCardInfo, len(members))
		for i, m := range members {
			cards[i] = s.memberCardInfoFromMember(ctx, tenantID, schoolName, m)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	return renderMemberCardsPDF(cards)
}

// orderMembersByIDs reorders a GetMembersByIDs result to match ids (the
// order the caller selected members in), dropping any id that matched no
// row -- same pattern as PrintCopyLabels' ordering of GetCopiesByIDs.
func orderMembersByIDs(members []domain.Member, ids []uuid.UUID) []domain.Member {
	byID := make(map[uuid.UUID]domain.Member, len(members))
	for _, m := range members {
		byID[m.UserID] = m
	}
	ordered := make([]domain.Member, 0, len(ids))
	for _, id := range ids {
		if m, found := byID[id]; found {
			ordered = append(ordered, m)
		}
	}
	return ordered
}

// PrintClearanceLetter renders the "bebas pustaka" clearance letter for a
// member already granted clearance; callers should call Clearance first
// and only print once it succeeds.
func (s *Service) PrintClearanceLetter(ctx context.Context, tenantID, memberUserID uuid.UUID) ([]byte, error) {
	if err := s.requireEnabled(ctx, tenantID); err != nil {
		return nil, err
	}
	var info memberCardInfo
	err := s.withTx(ctx, tenantID, func(ctx context.Context) error {
		member, found, err := s.repo.GetMember(ctx, tenantID, memberUserID)
		if err != nil {
			return err
		}
		if !found || member.Status != domain.MemberCleared {
			return domain.ErrMemberNotClearable
		}
		info = s.memberCardInfoFor(ctx, tenantID, memberUserID)
		return nil
	})
	if err != nil {
		return nil, err
	}
	vars := map[string]any{
		"SchoolName": info.SchoolName, "MemberName": info.MemberName, "MemberNo": info.MemberNo,
		"ClassName": info.ClassName, "IssuedOn": s.clock.Now().Format("2006-01-02"),
	}
	rendered, err := s.renderer.Render(ctx, documents.Template{Engine: documents.EngineHTML, Body: clearanceLetterTemplate}, vars)
	if err != nil {
		return nil, fmt.Errorf("render clearance letter: %w", err)
	}
	return rendered.PDF, nil
}
