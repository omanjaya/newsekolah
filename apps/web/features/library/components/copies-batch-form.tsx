"use client";

import { Button, Input, Select, useToast } from "@newsekolah/ui";
import { useTranslations } from "next-intl";
import type { ReactElement } from "react";
import { useState } from "react";

import {
  type LibraryCopiesBatchWrite,
  type LibraryCopyWrite,
  useCreateLibraryCopiesBatchMutation,
} from "../api";
import { useLibraryCatalogueOptionsQuery } from "../master-data-api";
import { useLibraryErrorMessage } from "../use-library-error-message";

const CONDITIONS: LibraryCopyWrite["condition"][] = ["good", "fair", "damaged", "lost"];

/** Adds several copies of the same title at once; every number is auto-generated by the API. */
export function CopiesBatchForm({
  titleId,
  onDone,
}: {
  titleId: string;
  onDone: () => void;
}): ReactElement {
  const t = useTranslations("app.library.copies.batchForm");
  const tCopies = useTranslations("app.library.copies");
  const tCondition = useTranslations("app.library.copies.condition");
  const toast = useToast();
  const libraryErrorMessage = useLibraryErrorMessage();
  const createBatch = useCreateLibraryCopiesBatchMutation();
  const options = useLibraryCatalogueOptionsQuery();

  const [count, setCount] = useState("1");
  const [condition, setCondition] = useState<LibraryCopyWrite["condition"]>("good");
  const [categoryId, setCategoryId] = useState("");
  const [locationId, setLocationId] = useState("");
  const [sourceId, setSourceId] = useState("");
  const [partnerId, setPartnerId] = useState("");
  const [error, setError] = useState("");

  const countValue = Number(count);
  const canSubmit = Number.isInteger(countValue) && countValue >= 1 && countValue <= 200;

  return (
    <form
      className="flex flex-col gap-4"
      onSubmit={(e) => {
        e.preventDefault();
        setError("");
        const body: LibraryCopiesBatchWrite = {
          count: countValue,
          condition,
          category_id: categoryId || undefined,
          location_id: locationId || undefined,
          source_id: sourceId || undefined,
          partner_id: partnerId || undefined,
          is_opac: true,
        };
        createBatch.mutate(
          { titleId, ...body },
          {
            onSuccess: (result) => {
              toast.success(t("saved", { count: result.data.length }));
              onDone();
            },
            onError: (err) => {
              setError(libraryErrorMessage(err));
            },
          },
        );
      }}
    >
      <label className="flex flex-col gap-1 text-[13px]">
        <span className="font-medium">{t("count")}</span>
        <Input
          type="number"
          min={1}
          max={200}
          value={count}
          onChange={(e) => {
            setCount(e.target.value);
          }}
          required
        />
      </label>
      <label className="flex flex-col gap-1 text-[13px]">
        <span className="font-medium">{tCopies("form.condition")}</span>
        <Select
          value={condition}
          onValueChange={(value) => {
            setCondition(value as LibraryCopyWrite["condition"]);
          }}
          options={CONDITIONS.map((value) => ({
            value: value as string,
            label: tCondition(value as string),
          }))}
        />
      </label>
      <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
        <label className="flex flex-col gap-1 text-[13px]">
          <span className="font-medium">{tCopies("form.category")}</span>
          <Select
            options={(options.data?.collection_categories ?? []).map((c) => ({
              value: c.id,
              label: c.name,
            }))}
            value={categoryId}
            onValueChange={setCategoryId}
            placeholder={tCopies("form.categoryPlaceholder")}
            disabled={options.isLoading}
          />
        </label>
        <label className="flex flex-col gap-1 text-[13px]">
          <span className="font-medium">{tCopies("form.location")}</span>
          <Select
            options={(options.data?.locations ?? []).map((l) => ({ value: l.id, label: l.name }))}
            value={locationId}
            onValueChange={setLocationId}
            placeholder={tCopies("form.locationPlaceholder")}
            disabled={options.isLoading}
          />
        </label>
        <label className="flex flex-col gap-1 text-[13px]">
          <span className="font-medium">{tCopies("form.source")}</span>
          <Select
            options={(options.data?.acquisition_sources ?? []).map((s) => ({
              value: s.id,
              label: s.name,
            }))}
            value={sourceId}
            onValueChange={setSourceId}
            placeholder={tCopies("form.sourcePlaceholder")}
            disabled={options.isLoading}
          />
        </label>
        <label className="flex flex-col gap-1 text-[13px]">
          <span className="font-medium">{tCopies("form.partner")}</span>
          <Select
            options={(options.data?.partners ?? []).map((p) => ({ value: p.id, label: p.name }))}
            value={partnerId}
            onValueChange={setPartnerId}
            placeholder={tCopies("form.partnerPlaceholder")}
            disabled={options.isLoading}
          />
        </label>
      </div>
      {error && <p className="text-[13px] text-status-absent">{error}</p>}
      <Button type="submit" loading={createBatch.isPending} disabled={!canSubmit}>
        {t("save")}
      </Button>
    </form>
  );
}
